#!/usr/bin/env python3
"""Bind a Docker test image to the unchanged provenance-bearing OCI archive.

This verifier accepts the bounded OCI layout generated by this release workflow.
Skopeo performs the import. Scanner layouts copy validated regular OCI members
into a fresh directory; tar metadata is never applied to the filesystem.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import tarfile

INDEX = "application/vnd.oci.image.index.v1+json"
MANIFEST = "application/vnd.oci.image.manifest.v1+json"
CONFIG = "application/vnd.oci.image.config.v1+json"
LAYER = "application/vnd.oci.image.layer.v1.tar"
INTOTO = "application/vnd.in-toto+json"
PROVENANCE = {"https://slsa.dev/provenance/v0.2", "https://slsa.dev/provenance/v1"}


def digest(stream) -> str:
    result = hashlib.sha256()
    while chunk := stream.read(1024 * 1024):
        result.update(chunk)
    return "sha256:" + result.hexdigest()


def file_digest(path: Path) -> str:
    with path.open("rb") as stream:
        return digest(stream)


class Archive:
    def __init__(self, source: tarfile.TarFile):
        self.source = source
        self.members = {}
        for member in source.getmembers():
            name = member.name.removeprefix("./")
            if PurePosixPath(name).is_absolute() or ".." in PurePosixPath(name).parts:
                raise ValueError("OCI archive contains an unsafe member name")
            if member.isdir():
                continue
            if not member.isfile() or name in self.members:
                raise ValueError("OCI archive contains a non-regular or duplicate member")
            self.members[name] = member
            if len(self.members) > 10000:
                raise ValueError("OCI archive exceeds the release member limit")

    def member(self, name: str):
        try:
            return self.source.extractfile(self.members[name])
        except KeyError:
            raise ValueError("OCI archive is missing a required member") from None

    def json(self, name: str, limit: int = 16 * 1024 * 1024) -> dict:
        with self.member(name) as stream:
            data = stream.read(limit + 1)
        if len(data) > limit:
            raise ValueError("OCI JSON exceeds its release size limit")
        value = json.loads(data)
        if not isinstance(value, dict):
            raise ValueError("OCI metadata must be a JSON object")
        return value

    def blob_name(self, descriptor: dict) -> str:
        identity = descriptor.get("digest", "")
        size = descriptor.get("size")
        if not re.fullmatch(r"sha256:[0-9a-f]{64}", identity) or type(size) is not int or size < 0:
            raise ValueError("OCI descriptor must contain a SHA256 digest and byte size")
        name = "blobs/sha256/" + identity.split(":")[1]
        member = self.members.get(name)
        if member is None or member.size != size:
            raise ValueError("OCI blob is missing or its size does not match")
        with self.member(name) as stream:
            if digest(stream) != identity:
                raise ValueError("OCI blob digest does not match")
        return name

    def blob_json(self, descriptor: dict, limit: int = 16 * 1024 * 1024) -> dict:
        return self.json(self.blob_name(descriptor), limit)


def inspect_archive(path: Path, architecture: str) -> dict:
    if architecture not in {"amd64", "arm64"}:
        raise ValueError("release architecture must be amd64 or arm64")
    leaves = []
    with tarfile.open(path, "r:*") as source:
        archive = Archive(source)
        if archive.json("oci-layout").get("imageLayoutVersion") != "1.0.0":
            raise ValueError("unsupported OCI layout version")

        def visit(index: dict, depth: int = 0):
            if depth > 8 or index.get("schemaVersion") != 2:
                raise ValueError("unsupported or excessively nested OCI index")
            for descriptor in index["manifests"]:
                media = descriptor.get("mediaType")
                value = archive.blob_json(descriptor)
                if media == INDEX:
                    visit(value, depth + 1)
                elif media == MANIFEST:
                    if value.get("schemaVersion") != 2:
                        raise ValueError("unsupported OCI manifest schema")
                    leaves.append((descriptor, value))
                    if len(leaves) > 100:
                        raise ValueError("OCI archive exceeds the release manifest limit")
                else:
                    raise ValueError("unsupported release OCI manifest media type")

        visit(archive.json("index.json"))
        candidates = [(descriptor, manifest) for descriptor, manifest in leaves
                      if descriptor.get("platform", {}).get("os") == "linux"
                      and descriptor.get("platform", {}).get("architecture") == architecture
                      and not manifest.get("artifactType")]
        if len(candidates) != 1:
            raise ValueError("OCI archive must contain exactly one matching runtime image")
        descriptor, manifest = candidates[0]
        if manifest["config"]["mediaType"] != CONFIG:
            raise ValueError("unsupported OCI runtime config media type")
        config = archive.blob_json(manifest["config"])
        if config.get("os") != "linux" or config.get("architecture") != architecture:
            raise ValueError("OCI config and selected platform disagree")
        rootfs = config["rootfs"]
        diff_ids = rootfs["diff_ids"]
        if rootfs.get("type") != "layers" or len(diff_ids) != len(manifest["layers"]):
            raise ValueError("OCI config and layer sequence disagree")
        for layer, expected in zip(manifest["layers"], diff_ids):
            name = archive.blob_name(layer)
            media = layer["mediaType"]
            with archive.member(name) as stream:
                if media == LAYER + "+gzip":
                    with gzip.GzipFile(fileobj=stream) as uncompressed:
                        actual = digest(uncompressed)
                elif media == LAYER:
                    actual = digest(stream)
                else:
                    raise ValueError("unsupported OCI layer compression; release expects gzip or uncompressed tar")
            if actual != expected:
                raise ValueError("OCI layer does not match its uncompressed diff ID")

        attestations = []
        for attestation_descriptor, attestation in leaves:
            annotations = attestation_descriptor.get("annotations", {})
            subject = attestation.get("subject", {}).get("digest")
            reference = annotations.get("vnd.docker.reference.digest")
            if subject != descriptor["digest"] and reference != descriptor["digest"]:
                continue
            if subject and reference and subject != reference:
                raise ValueError("OCI attestation subject and reference disagree")
            archive.blob_name(attestation["config"])
            for layer in attestation["layers"]:
                if layer["mediaType"] != INTOTO:
                    continue
                statement = archive.blob_json(layer, limit=128 * 1024 * 1024)
                if statement.get("predicateType") not in PROVENANCE:
                    continue
                if not any(item.get("digest", {}).get("sha256") == descriptor["digest"].split(":")[1]
                           for item in statement.get("subject", [])):
                    raise ValueError("provenance statement does not identify the runtime manifest")
                attestations.append({"manifest": attestation_descriptor["digest"],
                                     "statement": layer["digest"], "predicate_type": statement["predicateType"]})
        if not attestations:
            raise ValueError("release OCI archive has no matching build provenance")

    return {"format": "mas-release-image-binding/1", "archive": path.name,
            "archive_sha256": file_digest(path), "os": "linux", "architecture": architecture,
            "manifest_digest": descriptor["digest"], "config_digest": manifest["config"]["digest"],
            "diff_ids": diff_ids, "provenance": attestations, "docker_identity_verified": False}


def verify_import(path: Path, binding: dict, image: dict) -> dict:
    if binding.get("format") != "mas-release-image-binding/1" or file_digest(path) != binding["archive_sha256"]:
        raise ValueError("OCI archive changed after inspection")
    if (image.get("Id") != binding["config_digest"]
            or image.get("Os") != binding["os"]
            or image.get("Architecture") != binding["architecture"]
            or image.get("RootFS", {}).get("Type") != "layers"
            or image.get("RootFS", {}).get("Layers") != binding["diff_ids"]):
        raise ValueError("imported Docker image does not match the OCI config and root filesystem")
    return {**binding, "docker_identity_verified": True, "docker_image_id": image["Id"]}


def materialise_layout(path: Path, binding: dict, directory: Path) -> dict:
    """Give Trivy its supported directory input, selecting the tested manifest."""
    if (binding.get("format") != "mas-release-image-binding/1"
            or binding.get("docker_identity_verified") is not True
            or file_digest(path) != binding["archive_sha256"]):
        raise ValueError("scanner layout requires the unchanged, verified runtime archive")
    hashes = {}
    with tarfile.open(path, "r:*") as source:
        archive = Archive(source)
        names = archive.members.keys()
        if any(name not in {"index.json", "oci-layout"}
               and not re.fullmatch(r"blobs/sha256/[0-9a-f]{64}", name) for name in names):
            raise ValueError("unsupported scanner layout member name")
        # Existing directories (including symlinks) are rejected. Construct only
        # these known paths, not paths or permissions supplied by tar metadata.
        directory.mkdir(mode=0o700)
        (directory / "blobs" / "sha256").mkdir(parents=True, mode=0o700)
        for name in sorted(names):
            target = directory / name
            with archive.member(name) as incoming, target.open("xb") as outgoing:
                shutil.copyfileobj(incoming, outgoing, length=1024 * 1024)
            identity = file_digest(target)
            if name.startswith("blobs/") and identity != "sha256:" + name.rsplit("/", 1)[1]:
                raise ValueError("scanner layout blob does not match its digest")
            hashes[name] = identity
    if file_digest(path) != binding["archive_sha256"]:
        raise ValueError("OCI archive changed during scanner layout creation")
    original_index = hashes["index.json"]
    # Trivy 0.75 resolves an explicit reference only among root descriptors.
    # BuildKit's root references a nested index, so expose the already verified
    # runtime manifest directly in this scanner-only index. All content-addressed
    # blobs and the original archive/index/provenance remain unchanged.
    manifest_path = directory / "blobs" / "sha256" / binding["manifest_digest"].split(":")[1]
    scanner_index = {"schemaVersion": 2, "mediaType": INDEX, "manifests": [
        {"mediaType": MANIFEST, "digest": binding["manifest_digest"],
         "size": manifest_path.stat().st_size,
         "platform": {"os": binding["os"], "architecture": binding["architecture"]}}]}
    (directory / "index.json").write_text(json.dumps(scanner_index, sort_keys=True) + "\n")
    hashes["index.json"] = file_digest(directory / "index.json")
    return {**binding, "scanner_layout_verified": True,
            "scanner_original_index_sha256": original_index,
            "scanner_directory": str(directory), "scanner_layout_files": hashes,
            "scanner_input": str(directory) + "@" + binding["manifest_digest"]}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--architecture", required=True, choices=("amd64", "arm64"))
    parser.add_argument("--binding", required=True, type=Path)
    parser.add_argument("--docker-inspect", type=Path, help="verify imported image against a preceding binding")
    parser.add_argument("--layout-directory", type=Path, help="materialise a fresh OCI directory for Trivy")
    args = parser.parse_args()
    if args.docker_inspect and args.layout_directory:
        parser.error("verify the import before creating the scanner layout")
    if args.docker_inspect or args.layout_directory:
        binding = json.loads(args.binding.read_text())
        if binding["architecture"] != args.architecture:
            raise ValueError("requested architecture differs from the archive binding")
        if args.layout_directory:
            binding = materialise_layout(args.archive, binding, args.layout_directory)
        else:
            images = json.loads(args.docker_inspect.read_text())
            if len(images) != 1:
                raise ValueError("expected exactly one imported Docker image")
            binding = verify_import(args.archive, binding, images[0])
    else:
        binding = inspect_archive(args.archive, args.architecture)
    args.binding.write_text(json.dumps(binding, indent=2, sort_keys=True) + "\n")
    print(json.dumps(binding, sort_keys=True))


if __name__ == "__main__":
    main()
